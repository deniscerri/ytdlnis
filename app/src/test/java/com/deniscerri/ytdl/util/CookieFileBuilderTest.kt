package com.deniscerri.ytdl.util

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class CookieFileBuilderTest {

    private fun entry(url: String, vararg cookies: String): String {
        val builder = StringBuilder()
        builder.append("# ").append(url).append("\n")
        builder.append("# Generated by YTDLnis\n")
        cookies.forEach { builder.append(it).append("\n") }
        return builder.toString()
    }

    private fun cookie(name: String, value: String): String {
        return ".instagram.com\tTRUE\t/\tTRUE\t1799999999\t$name\t$value"
    }

    @Test
    fun build_singleEntry_containsOnlyCookieLines() {
        val content = entry(
            "https://instagram.com/",
            cookie("sessionid", "ABC123"),
            cookie("csrftoken", "XYZ")
        )

        val result = CookieFileBuilder.build(listOf(content))

        val expected = CookieFileBuilder.HEADER +
                cookie("sessionid", "ABC123") + "\n" +
                cookie("csrftoken", "XYZ") + "\n"

        assertEquals(expected, result)
    }

    @Test
    fun build_sameUrlDifferentDescriptions_keepsAllCookieLines() {
        val first = entry("https://instagram.com/", cookie("sessionid", "FIRST_SESSION"))
        val second = entry("https://instagram.com/", cookie("sessionid", "SECOND_SESSION"))

        val result = CookieFileBuilder.build(listOf(first, second))

        assertTrue(result.contains(cookie("sessionid", "FIRST_SESSION") + "\n"))
        assertTrue(result.contains(cookie("sessionid", "SECOND_SESSION") + "\n"))
        assertEquals(1, result.lines().count { it == cookie("sessionid", "FIRST_SESSION") })
        assertEquals(1, result.lines().count { it == cookie("sessionid", "SECOND_SESSION") })
    }

    @Test
    fun build_prefixCookieValue_keepsBothLines() {
        val first = entry("https://instagram.com/", cookie("sessionid", "ABC123LONG"))
        val second = entry("https://instagram.com/", cookie("sessionid", "ABC123"))

        val result = CookieFileBuilder.build(listOf(first, second))

        assertTrue(result.contains(cookie("sessionid", "ABC123LONG") + "\n"))
        assertTrue(result.contains(cookie("sessionid", "ABC123") + "\n"))
        assertEquals(2, result.lines().count { it.startsWith(".instagram.com") })
    }

    @Test
    fun build_duplicateCookieLine_appearsOnlyOnce() {
        val first = entry("https://instagram.com/", cookie("sessionid", "ABC123"))
        val second = entry("https://instagram.com/", cookie("sessionid", "ABC123"))

        val result = CookieFileBuilder.build(listOf(first, second))

        assertEquals(1, result.lines().count { it == cookie("sessionid", "ABC123") })
    }

    @Test
    fun build_noCookies_containsOnlyHeader() {
        assertEquals(CookieFileBuilder.HEADER, CookieFileBuilder.build(emptyList()))
    }

    @Test
    fun build_headerIsNewlineTerminated() {
        val content = entry("https://instagram.com/", cookie("sessionid", "ABC123"))

        val result = CookieFileBuilder.build(listOf(content))

        assertTrue(CookieFileBuilder.HEADER.endsWith("\n"))
        assertTrue(result.startsWith(CookieFileBuilder.HEADER))
        assertFalse(result.contains("Do not edit.#"))
    }

    @Test
    fun build_contentWithExistingHeader_skipsHeaderAndComments() {
        val content = CookieFileBuilder.HEADER +
                entry("https://instagram.com/", cookie("sessionid", "ABC123"))

        val result = CookieFileBuilder.build(listOf(content))

        assertEquals(1, result.lines().count { it == "# Netscape HTTP Cookie File" })
        assertEquals(1, result.lines().count { it == "# WebView Generated by the YTDLnis app" })
        assertEquals(1, result.lines().count { it == "# This is a generated file! Do not edit." })
        assertEquals(0, result.lines().count { it == "# https://instagram.com/" })
        assertEquals(0, result.lines().count { it == "# Generated by YTDLnis" })
        assertEquals(1, result.lines().count { it == cookie("sessionid", "ABC123") })
    }

    @Test
    fun build_blankLines_areIgnored() {
        val content = "\n" +
                "# https://instagram.com/\n" +
                "\n" +
                cookie("sessionid", "ABC123") + "\n" +
                "\n" +
                "   \n" +
                cookie("csrftoken", "XYZ") + "\n"

        val result = CookieFileBuilder.build(listOf(content))

        val expected = CookieFileBuilder.HEADER +
                cookie("sessionid", "ABC123") + "\n" +
                cookie("csrftoken", "XYZ") + "\n"

        assertEquals(expected, result)
        assertTrue(result.lines().filter { it.isNotEmpty() }.all { it.isNotBlank() })
    }

    @Test
    fun build_emptyCookieValue_keepsTrailingTab() {
        val result = CookieFileBuilder.build(listOf(entry("https://instagram.com/", cookie("empty", ""))))

        assertTrue(result.lines().any { it == cookie("empty", "") && it.split("\t").size == 7 })
    }

    @Test
    fun build_keepsHttpOnlyPrefix() {
        val content = entry("https://instagram.com/", "#HttpOnly_.instagram.com\tTRUE\t/\tTRUE\t1799999999\tsessionid\tABC123")

        val result = CookieFileBuilder.build(listOf(content))

        assertTrue(result.contains("#HttpOnly_.instagram.com\tTRUE\t/\tTRUE\t1799999999\tsessionid\tABC123\n"))
    }
}
