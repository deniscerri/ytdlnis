import java.util.Date


class CookieViewModel(private val application: Application) : AndroidViewModel(application) {
    private val repository: CookieRepository
    val items: LiveData<List<CookieItem>>

    private val projection = arrayOf(
        CookieObject.HOST,
        CookieObject.EXPIRY,
        CookieObject.PATH,
        CookieObject.NAME,
        CookieObject.VALUE,
        CookieObject.SECURE
    )

    init {
        val dao = DBManager.getInstance(application).cookieDao
        repository = CookieRepository(dao, application)
        items = repository.items.asLiveData()
    }

    fun getAll(): List<CookieItem> {
        return repository.getAll()
    }

    private fun getByURL(url: String) : CookieItem? {
        return repository.getByURL(url)
    }

    private fun getByURLDescription(url: String, description: String): CookieItem? {
        return repository.getByURLDescription(url, description)
    }

    suspend fun insert(item: CookieItem) : Long {
        val exists = getByURLDescription(item.url, item.description)
        if (exists != null) {
            exists.content = item.content
            repository.update(exists)
            return exists.id
        }

        return repository.insert(item)
    }

    fun delete(item: CookieItem) = viewModelScope.launch(Dispatchers.IO) {
        repository.delete(item)
        updateCookiesFile()
    }

    suspend fun changeCookieEnabledState(itemId: Long, isEnabled: Boolean) {
        repository.changeCookieEnabledState(itemId, isEnabled)
        updateCookiesFile()
    }

    fun deleteAll() = viewModelScope.launch(Dispatchers.IO) {
        repository.deleteAll()
    }

    fun update(item: CookieItem) = viewModelScope.launch(Dispatchers.IO) {
        repository.update(item)
    }

    object CookieObject {
        const val NAME = "name"
        const val VALUE = "value"
        const val SECURE = "is_secure"
        const val EXPIRY = "expires_utc"
        const val HOST = "host_key"
        const val PATH = "path"
    }

    @SuppressLint("SdCardPath")
    fun getCookiesFromDB(url: String) : Result<String> = kotlin.runCatching {
        CookieManager.getInstance().flush()

        val targetHost = Uri.parse(if (url.contains("://")) url else "https://$url").host
            ?: throw Exception("Invalid URL or domain!")
        // login cookies usually live on the parent domain, music.youtube.com gets them from .youtube.com
        val parentDomain = targetHost.split('.').takeLast(2).joinToString(".")

        val dbCookies = runCatching { readCookiesDB(targetHost, parentDomain) }
            .onFailure { Log.e("CookieViewModel", "Reading the webview cookie store failed", it) }
            .getOrDefault(listOf())

        // some webviews (e.g. GrapheneOS Vanadium) keep the store somewhere else or encrypt the values,
        // the cookie manager still has them since the user stays logged in
        val cookieList = dbCookies.takeIf { list -> list.any { it.value.isNotBlank() } }
            ?: cookiesFromCookieManager(url, targetHost, parentDomain)

        if (cookieList.isEmpty()) throw Exception("No cookies found for $targetHost")

        "# $url\n" +
        "# Generated by YTDLnis\n" +
        cookieList.fold(StringBuilder("")) { acc, cookie ->
            acc.append(cookie.toNetscapeFormat()).append("\n")
        }.toString()
    }

    private fun cookiesFromCookieManager(url: String, targetHost: String, parentDomain: String) : List<WebViewActivity.CookieItem> {
        val pageUrl = if (url.contains("://")) url else "https://$targetHost"
        val raw = CookieManager.getInstance().getCookie(pageUrl) ?: return listOf()
        // getCookie gives only name=value pairs, so path, secure and expiry get defaults yt-dlp accepts
        val expiry = System.currentTimeMillis() / 1000 + 365L * 24 * 60 * 60
        return raw.split(";").mapNotNull { pair ->
            val name = pair.substringBefore("=").trim()
            if (name.isEmpty() || !pair.contains("=")) return@mapNotNull null
            WebViewActivity.CookieItem(
                domain = ".$parentDomain",
                name = name,
                value = pair.substringAfter("=").trim(),
                path = "/",
                secure = true,
                expiry = expiry
            )
        }
    }

    @SuppressLint("SdCardPath")
    private fun readCookiesDB(targetHost: String, parentDomain: String) : List<WebViewActivity.CookieItem> {
        // not /data/data/<package>: secondary users, work profiles and app clones live in /data/user/<id>/<package>
        // the incognito webview runs in its own process with its own data dir (App.kt setDataDirectorySuffix), read that store and not the normal one
        val incognito = Build.VERSION.SDK_INT >= Build.VERSION_CODES.P &&
            Application.getProcessName().endsWith(":incognito_process")
        val dbPath = File(application.applicationInfo.dataDir).walkTopDown()
            .find { it.name == "Cookies" && it.path.contains("incognito_store") == incognito }
            ?: throw Exception("Cookies File not found!")

        val db = SQLiteDatabase.openDatabase(
            dbPath.absolutePath, null, OPEN_READONLY
        )

        val cookieList = mutableListOf<WebViewActivity.CookieItem>()

        val selection = "${CookieObject.HOST} LIKE ? OR ${CookieObject.HOST} LIKE ?"
        val selectionArgs = arrayOf(
            "%$targetHost",          // Matches 'example.com' or '.example.com'
            "%$parentDomain"         // Matches the parent domain if 'www.example.com' or 'music.example.com' passed
        )

        db.query(
            "cookies", projection, selection, selectionArgs, null, null, null
        ).run {
            while (moveToNext()) {
                val expiry = getLong(getColumnIndexOrThrow(CookieObject.EXPIRY))
                val name = getString(getColumnIndexOrThrow(CookieObject.NAME))
                val value = getString(getColumnIndexOrThrow(CookieObject.VALUE))
                val path = getString(getColumnIndexOrThrow(CookieObject.PATH))
                val secure = getLong(getColumnIndexOrThrow(CookieObject.SECURE)) == 1L
                val hostKey = getString(getColumnIndexOrThrow(CookieObject.HOST))


                val host = if (hostKey[0] != '.') ".$hostKey" else hostKey
                cookieList.add(
                    WebViewActivity.CookieItem(
                        domain = host,
                        name = name,
                        value = value,
                        path = path,
                        secure = secure,
                        expiry = expiry
                    )
                )
            }
            close()
        }
        db.close()
        return cookieList
    }

    fun updateCookiesFile() = viewModelScope.launch(Dispatchers.IO) {
        repository.updateCookieFile()
    }

    suspend fun importFromClipboard() {
        try{
            val clipboard: ClipboardManager =
                application.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
            var clip = clipboard.primaryClip!!.getItemAt(0).text
            Log.e("Aaa", clip.toString())

            if (clip.startsWith("# Netscape HTTP Cookie File")){
                clip = clip.removePrefix(CookieRepository.cookieHeader)
                val cookie = CookieItem(
                    0,
                    "",
                    clip.toString(),
                    "Cookie Import at [${Date()}]",
                    true
                )
                insert(cookie)
                updateCookiesFile()
            }
        }catch (e: Exception){
            e.printStackTrace()
        }
    }

    fun exportToClipboard() = viewModelScope.launch {
        try{
            val clipboard: ClipboardManager =
                application.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
            FileUtil.getCookieFile(application, true){c ->
                val cookieFile = File(c)
                if (! cookieFile.exists()) updateCookiesFile()
                cookieFile.readText().let {
                    clipboard.setText(it)
                }
            }

        }catch (e: Exception){
            e.printStackTrace()
        }
    }

    fun exportToFile(exported: (File?) -> Unit) = viewModelScope.launch(Dispatchers.IO) {
        try{
            FileUtil.getCookieFile(application, true){ c ->
                val cookieFile = File(c)
                if (!cookieFile.exists()) updateCookiesFile()

                val dir = File("${FileUtil.getCachePath(application)}/Cookie Backups")
                dir.mkdirs()
                val saveFile = File("${dir.absolutePath}/YTDLnis_Cookies.txt")

                saveFile.delete()
                saveFile.createNewFile()
                cookieFile.copyTo(saveFile, true)

                val res = runBlocking {
                    FileUtil.moveFile(saveFile.parentFile!!, application, FileUtil.getDefaultApplicationPath(), false) {}
                }

                exported(File(res[0]))
            }
        }catch (e: Exception){
            e.printStackTrace()
            exported(null)
        }
    }

}